extern void gfx_get_clip(int* x1, int* y1, int* x2, int* y2);

void font_draw_char(uint32_t* buffer, int buf_w, int buf_h, int x, int y, char c, uint32_t fg, uint32_t bg, int transparent) {
    uint8_t uc = (uint8_t)c;
    int cx1 = 0, cy1 = 0, cx2 = buf_w, cy2 = buf_h;
    gfx_get_clip(&cx1, &cy1, &cx2, &cy2);
    if (cx1 < 0) cx1 = 0;
    if (cy1 < 0) cy1 = 0;
    if (cx2 > buf_w) cx2 = buf_w;
    if (cy2 > buf_h) cy2 = buf_h;

    if (x + FONT_WIDTH <= cx1 || x >= cx2 || y + FONT_HEIGHT <= cy1 || y >= cy2) return;

    for (int row = 0; row < FONT_HEIGHT; row++) {
        int py = y + row;
        if (py < cy1 || py >= cy2) continue;
        uint8_t bits = font_data[uc][row];
        for (int col = 0; col < FONT_WIDTH; col++) {
            int px = x + col;
            if (px < cx1 || px >= cx2) continue;
            if (bits & (1 << (7 - col))) {
                buffer[py * buf_w + px] = fg;
            } else if (!transparent) {
                buffer[py * buf_w + px] = bg;
            }
        }
    }
}

void font_draw_char_scaled(uint32_t* buffer, int buf_w, int buf_h, int x, int y, char c, uint32_t fg, int scale) {
    if (scale <= 1) {
        font_draw_char(buffer, buf_w, buf_h, x, y, c, fg, 0, 1);
        return;
    }
    uint8_t uc = (uint8_t)c;
    int cx1 = 0, cy1 = 0, cx2 = buf_w, cy2 = buf_h;
    gfx_get_clip(&cx1, &cy1, &cx2, &cy2);
    if (cx1 < 0) cx1 = 0;
    if (cy1 < 0) cy1 = 0;
    if (cx2 > buf_w) cx2 = buf_w;
    if (cy2 > buf_h) cy2 = buf_h;

    int char_w = FONT_WIDTH * scale;
    int char_h = FONT_HEIGHT * scale;
    if (x + char_w <= cx1 || x >= cx2 || y + char_h <= cy1 || y >= cy2) return;

    for (int row = 0; row < FONT_HEIGHT; row++) {
        uint8_t bits = font_data[uc][row];
        for (int col = 0; col < FONT_WIDTH; col++) {
            if (bits & (1 << (7 - col))) {
                for (int dy = 0; dy < scale; dy++) {
                    int py = y + row * scale + dy;
                    if (py < cy1 || py >= cy2) continue;
                    for (int dx = 0; dx < scale; dx++) {
                        int px = x + col * scale + dx;
                        if (px < cx1 || px >= cx2) continue;
                        buffer[py * buf_w + px] = fg;
                    }
                }
            }
        }
    }
}

void font_draw_string_scaled(uint32_t* buffer, int buf_w, int buf_h, int x, int y, const char* str, uint32_t fg, int scale) {
    if (!str || scale <= 0) return;
    int cur_x = x;
    while (*str) {
        font_draw_char_scaled(buffer, buf_w, buf_h, cur_x, y, *str, fg, scale);
        cur_x += FONT_WIDTH * scale;
        str++;
    }
}

void font_draw_string(uint32_t* buffer, int buf_w, int buf_h, int x, int y, const char* str, uint32_t fg, uint32_t bg, int transparent) {
    int cur_x = x;
    int cur_y = y;
    while (*str) {
        if (*str == '\n') {
            cur_x = x;
            cur_y += FONT_HEIGHT + 2;
        } else {
            font_draw_char(buffer, buf_w, buf_h, cur_x, cur_y, *str, fg, bg, transparent);
            cur_x += FONT_WIDTH;
        }
        str++;
    }
}

void font_draw_string_clipped(uint32_t* buffer, int buf_w, int buf_h, int x, int y, int max_w, const char* str, uint32_t fg, uint32_t bg, int transparent) {
    if (max_w <= 0 || !str) return;
    int cur_x = x;
    int cur_y = y;
    while (*str) {
        if (*str == '\n') {
            cur_x = x;
            cur_y += FONT_HEIGHT + 2;
        } else {
            if (cur_x + FONT_WIDTH > x + max_w) {
                break;
            }
            font_draw_char(buffer, buf_w, buf_h, cur_x, cur_y, *str, fg, bg, transparent);
            cur_x += FONT_WIDTH;
        }
        str++;
    }
}

void font_draw_string_ellipsis(uint32_t* buffer, int buf_w, int buf_h, int x, int y, int max_w, const char* str, uint32_t fg, uint32_t bg, int transparent) {
    if (max_w <= 0 || !str) return;
    int str_w = font_get_string_width(str);
    if (str_w <= max_w) {
        font_draw_string_clipped(buffer, buf_w, buf_h, x, y, max_w, str, fg, bg, transparent);
        return;
    }
    int avail_w = max_w - 3 * FONT_WIDTH;
    if (avail_w <= 0) {
        font_draw_string_clipped(buffer, buf_w, buf_h, x, y, max_w, "...", fg, bg, transparent);
        return;
    }
    int cur_x = x;
    while (*str && (cur_x + FONT_WIDTH <= x + avail_w)) {
        if (*str == '\n') break;
        font_draw_char(buffer, buf_w, buf_h, cur_x, y, *str, fg, bg, transparent);
        cur_x += FONT_WIDTH;
        str++;
    }
    for (int i = 0; i < 3; i++) {
        font_draw_char(buffer, buf_w, buf_h, cur_x, y, '.', fg, bg, transparent);
        cur_x += FONT_WIDTH;
    }
}

int font_get_string_width(const char* str) {
    int max_w = 0;
    int cur_w = 0;
    while (*str) {
        if (*str == '\n') {
            if (cur_w > max_w) max_w = cur_w;
            cur_w = 0;
        } else {
            cur_w += FONT_WIDTH;
        }
        str++;
    }
    if (cur_w > max_w) max_w = cur_w;
    return max_w;
}

